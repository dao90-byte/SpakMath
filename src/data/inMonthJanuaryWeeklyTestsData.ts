function cg(
  id: string,
  label: string,
  icon: string,
  count: number,
  unitValue: number,
  color: string,
  isUnknown = false,
  displayMode: CPAConcreteGroup['displayMode'] = 'measurement'
): CPAConcreteGroup {
  return {
    id,
    label,
    icon,
    count,
    unitValue,
    totalValue: count * unitValue,
    color,
    isUnknown,
    displayMode,
  };
}

