function makeBarSpec(
  id: string,
  label: string,
  units: number,
  unitValue: number,
  offsetValue: number,
  color: string,
  displayValue: string,
  extra?: {
    isUnknown?: boolean;
    hideOffsetBeforeSolve?: boolean;
    highlightNote?: string;
    deltaType?: 'added' | 'removed' | 'transferred_in' | 'transferred_out';
  }
): BarModelBarSpec {
  return makeBarSpecObj({
    id,
    label,
    units,
    unitValue,
    offsetValue,
    color,
    displayValue,
    ...extra,
  });
}

